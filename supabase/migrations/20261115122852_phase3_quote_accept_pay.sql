-- Phase 3: quotes the customer can accept and pay without emails back and
-- forth. Adds the token + the owner's quote-settings columns to
-- quote_requests, plus the RPC the public /presupuesto/<token> page uses.

ALTER TABLE public.quote_requests
  ADD COLUMN IF NOT EXISTS quote_token             text,
  ADD COLUMN IF NOT EXISTS quote_price_cents       integer,
  ADD COLUMN IF NOT EXISTS quote_shipping_cents    integer NOT NULL DEFAULT 0,
  ADD COLUMN IF NOT EXISTS quote_production_days   integer,
  ADD COLUMN IF NOT EXISTS quote_message           text,
  ADD COLUMN IF NOT EXISTS quote_sent_at           timestamptz,
  ADD COLUMN IF NOT EXISTS quote_expires_at        timestamptz,
  ADD COLUMN IF NOT EXISTS quote_fulfillment       text,
  ADD COLUMN IF NOT EXISTS quote_stripe_link       text,
  ADD COLUMN IF NOT EXISTS quote_paid_at           timestamptz,
  ADD COLUMN IF NOT EXISTS quote_reminder_sent_at  timestamptz;

-- Backfill tokens for existing rows that are missing one.
UPDATE public.quote_requests
SET    quote_token = translate(encode(gen_random_bytes(18), 'base64'), '+/=', '-_.')
WHERE  quote_token IS NULL;

ALTER TABLE public.quote_requests
  ALTER COLUMN quote_token SET DEFAULT translate(encode(gen_random_bytes(18), 'base64'), '+/=', '-_.');

ALTER TABLE public.quote_requests
  ALTER COLUMN quote_token SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_indexes
    WHERE schemaname = 'public' AND indexname = 'quote_requests_quote_token_key'
  ) THEN
    ALTER TABLE public.quote_requests
      ADD CONSTRAINT quote_requests_quote_token_key UNIQUE (quote_token);
  END IF;
END$$;

CREATE INDEX IF NOT EXISTS quote_requests_quote_token_idx ON public.quote_requests(quote_token);

-- Public RPC. Returns only what /presupuesto/<token> needs to render; no
-- phone, no admin internals. Signed URLs for files are generated by the
-- same page via a small admin-free signed-url bucket policy (read-only).
CREATE OR REPLACE FUNCTION public.get_quote_by_token(_token text)
RETURNS TABLE (
  id uuid,
  created_at timestamptz,
  quote_sent_at timestamptz,
  quote_expires_at timestamptz,
  quote_paid_at timestamptz,
  quote_price_cents integer,
  quote_shipping_cents integer,
  quote_production_days integer,
  quote_message text,
  quote_fulfillment text,
  quote_stripe_link text,
  material text,
  color text,
  infill text,
  wall_loops integer,
  pieces jsonb,
  first_name text,
  page_language text
)
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT
    q.id,
    q.created_at,
    q.quote_sent_at,
    q.quote_expires_at,
    q.quote_paid_at,
    q.quote_price_cents,
    q.quote_shipping_cents,
    q.quote_production_days,
    q.quote_message,
    q.quote_fulfillment,
    q.quote_stripe_link,
    q.material,
    q.color,
    q.infill,
    q.wall_loops,
    COALESCE(q.pieces, '[]'::jsonb) AS pieces,
    NULLIF(split_part(COALESCE(q.contact_email, ''), '@', 1), '') AS first_name,
    q.page_language
  FROM public.quote_requests q
  WHERE q.quote_token = _token
    AND q.quote_sent_at IS NOT NULL
  LIMIT 1;
$$;

REVOKE ALL ON FUNCTION public.get_quote_by_token(text) FROM public;
GRANT EXECUTE ON FUNCTION public.get_quote_by_token(text) TO anon, authenticated;
